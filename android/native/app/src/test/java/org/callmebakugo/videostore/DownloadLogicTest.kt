package org.callmebakugo.videostore

/** Dependency-free JVM regression checks; run :app:testDownloadLogic. */
fun main() {
    var checks = 0
    fun verify(value: Boolean) { check(value); checks++ }
    verify(parseDownloadProgress("VS| 42.8%| 2.50MiB/s|00:17") == DownloadProgress(42, "2.50MiB/s", "00:17"))
    verify(parseDownloadProgress("VS|NA|NA|Unknown") == DownloadProgress(null, "", ""))
    verify(parseDownloadProgress("VS|105%| 1MiB/s | 00:00 ")?.percent == 100)
    verify(parseDownloadProgress("VS|bad|NA|NA")?.percent == null)
    verify(parseDownloadProgress("[download] Destination: video.mp4") == null)
    verify(parseDownloadProgress("VS|50%") == null)
    verify(isConversionLine("[ExtractAudio] Destination: audio.mp3"))
    verify(isConversionLine("[Merger] Merging formats into video.mp4"))
    verify(!isConversionLine("[download] 100%"))
    verify(safeMediaName("a/b\\c:\nname?", "mp3") == "a_b_c__name_.mp3")
    verify(safeMediaName("  ", "webm") == "VideoStore.webm")
    verify(safeMediaName("x".repeat(200), "mp4").length == 124)
    verify(friendlyError("ERROR: No space left on device").contains("storage"))
    verify(friendlyError("Connection timed out").contains("connection"))
    verify(friendlyError("HTTP Error 403").contains("refused"))
    verify(friendlyError("private video").contains("sign-in"))
    verify(friendlyError("unrecognized failure").contains("technical details"))
    verify(setOf("Fetching details", "Converting", "Saving", "Waiting for Wi-Fi", "Cancelling").all { it in activeStatuses })
    verify(listOf("Failed", "Cancelled", "Complete").none { it in activeStatuses })
    verify(parseInputUrls(" https://example.com/a\nhttps://example.com/b https://example.com/a ") == listOf("https://example.com/a", "https://example.com/b"))
    verify(runCatching { parseInputUrls(" ") }.isFailure)
    verify(runCatching { parseInputUrls("https://example.com/a file:///tmp/a") }.isFailure)
    verify(runCatching { parseInputUrls("https:///missing-host") }.isFailure)
    verify(!isMediaUrl("javascript:alert(1)"))
    val parent = Job("parent", "https://example.com/playlist", 3, playlist = true, destination = "content://provider/tree/audio", destinationLabel = "Music")
    val entries = listOf(playlistEntry(1, "https://example.com/one", "One"), playlistEntry(4, "opaque-id", ""))
    val children = playlistChildren(parent, entries)
    verify(children.size == 2 && children.map { it.title } == listOf("One", "Playlist item 4"))
    verify(children[0].url == "https://example.com/one" && children[0].playlistIndex == 0)
    verify(children[1].url == parent.url && children[1].playlistIndex == 4)
    verify(children.all { it.destination == parent.destination && it.destinationLabel == "Music" && it.format == 3 && it.parentId == "parent" && !it.playlist && it.status == "Queued" })
    verify(children.map { it.id }.distinct().size == 2)
    verify(sameSubmission(parent, parent.url, 3, parent.destination, true))
    verify(!sameSubmission(parent, parent.url, 3, "", true))
    verify(!sameSubmission(parent, parent.url, 3, parent.destination, false))
    verify(destinationKind(0) == "video" && destinationKind(2) == "video" && destinationKind(3) == "audio" && destinationKind(4) == "audio")
    verify(safeMediaName("猫".repeat(100), "mp4").toByteArray(Charsets.UTF_8).size <= 124)
    verify(recoveredPublicationStatus("Saving", true) == "Complete")
    verify(recoveredPublicationStatus("Saving", false) == "Queued")
    verify(recoveredPublicationStatus("Cancelling", false) == "Cancelled")
    verify(recoveredPublicationStatus("Failed", false) == "Failed")
    verify(recoveredPublicationStatus("Failed", true) == "Complete")
    verify("Reading playlist" in activeStatuses)
    println("Download logic: $checks checks passed")
}
